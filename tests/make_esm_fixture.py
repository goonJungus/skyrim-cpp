"""Generate a synthetic Skyrim.esm for end-to-end tests of the form database.

This is OUR OWN synthetic data written to the documented TES4 container layout.
No game content is involved -- record names and names inside them are
invented. The point is to exercise the reader against a known-good structure:

  * TES4 header record (HEDR / CNAM / SNAM)
  * top-level GRUPs (WRLD, CELL, STAT, NPC_, SCPT)
  * nested GRUP inside a group, holding ACHR (tests recursion)
  * a zlib-compressed record payload (flag 0x00040000)
  * a record with formID 0 (must be skipped as an unused slot)
  * records with EDID / FULL subrecords (must decode to strings)

Usage:  python make_esm_fixture.py <output-dir>
"""
import os
import struct
import sys
import zlib

# --- container primitives ---------------------------------------------------

def record(rtype: str, form_id: int, payload: bytes, compressed: bool = False) -> bytes:
    """A 24-byte record header + payload.

    A compressed record body is framed as a u32 decompressed size followed by
    the zlib stream (RFC 1950) -- the real ESM layout, not a bare zlib stream.
    """
    flags = 0x00040000 if compressed else 0
    if compressed:
        data = struct.pack('<I', len(payload)) + zlib.compress(payload)
    else:
        data = payload
    hdr = (rtype.encode('ascii').ljust(4, b'\0')[:4]
           + struct.pack('<III', len(data), flags, form_id)
           + struct.pack('<HHHH', 0, 0, 44, 0))
    assert len(hdr) == 24, len(hdr)
    return hdr + data


def group(label: str, children: bytes, group_type: int = 0) -> bytes:
    """A 24-byte GRUP header + children. groupSize includes the header."""
    body = (label.encode('ascii').ljust(4, b'\0')[:4]
            + struct.pack('<i', group_type)
            + struct.pack('<HHI', 0, 0, 0))
    assert len(body) == 16, len(body)
    size = 24 + len(children)
    hdr = b'GRUP' + struct.pack('<I', size) + body
    assert len(hdr) == 24, len(hdr)
    return hdr + children


def sub(rtype: str, payload: bytes) -> bytes:
    """A subrecord: 4-byte type, u16 size, data."""
    return (rtype.encode('ascii').ljust(4, b'\0')[:4]
            + struct.pack('<H', len(payload)) + payload)


def zstr(s: str) -> bytes:
    return s.encode('ascii') + b'\0'


# --- content ----------------------------------------------------------------

def build() -> bytes:
    out = bytearray()

    # TES4 file header. HEDR = float version, int32 recordCount, u32 nextObjectId
    tes4_payload = (
        sub('HEDR', struct.pack('<fii', 1.7, 12, 0x000800))
        + sub('CNAM', zstr("Synthetic Test Fixture"))
        + sub('SNAM', zstr("Generated by make_esm_fixture.py - no game content"))
    )
    out += record('TES4', 0, bytes(tes4_payload))

    # --- WRLD: worldspaces (EDID decodable) ---
    world_records = b''
    for i, (edid, full) in enumerate([
        ("FixtureWorldA", "Fixture World A"),
        ("FixtureWorldB", "Fixture World B"),
        ("FixtureInterior", "Fixture Interior"),
    ]):
        payload = sub('EDID', zstr(edid)) + sub('FULL', zstr(full))
        world_records += record('WRLD', 0x100 + i, payload)
    out += group('WRLD', world_records)

    # --- CELL: includes an interior flag and one empty-formID slot ---
    cell_records = b''
    for i, (edid, full, interior) in enumerate([
        ("FixtureCell00", "Fixture Cell 00", 0),
        ("FixtureCell01", "Fixture Cell 01", 0),
        ("FixtureCellIn", "Fixture Interior Cell", 1),
    ]):
        payload = (sub('EDID', zstr(edid))
                   + sub('FULL', zstr(full))
                   + sub('DATA', bytes([interior & 1, 0, 0, 0]))
                   + sub('XCLC', struct.pack('<ii', i - 2, i - 2)))
        cell_records += record('CELL', 0x200 + i, payload)
    # unused slot: formID 0 must be skipped by the reader
    cell_records += record('CELL', 0, sub('EDID', zstr("UnusedSlotShouldBeSkipped")))
    # a REFR nested directly inside the CELL group
    refr_payload = (sub('NAME', struct.pack('<I', 0x300))
                    + sub('DATA', struct.pack('<6f', 1.0, 2.0, 3.0, 0.0, 0.0, 0.0)))
    cell_records += record('REFR', 0x210, refr_payload)
    out += group('CELL', cell_records)

    # --- STAT: one UNCOMPRESSED and one ZLIB-COMPRESSED record ---
    stat_plain = sub('EDID', zstr("FixtureStatPlain")) + sub('FULL', zstr("Plain Prop"))
    out += group('STAT', record('STAT', 0x300, stat_plain, compressed=False))

    stat_z = sub('EDID', zstr("FixtureStatCompressed")) + sub('FULL', zstr("Compressed Prop"))
    stat_z += sub('MODL', b'\x00' * 512)      # filler so deflate actually compresses
    out += group('STAT', record('STAT', 0x301, stat_z, compressed=True))

    # --- NPC_ with a NESTED group holding ACHR (exercises recursion) ---
    npc_payload = sub('EDID', zstr("FixtureNpc")) + sub('FULL', zstr("Fixture NPC"))
    achr_payload = sub('EDID', zstr("FixtureActor")) + sub('FULL', zstr("Fixture Actor"))
    nested = group('ACHR', record('ACHR', 0x401, achr_payload), group_type=1)
    out += group('NPC_', record('NPC_', 0x400, npc_payload) + nested)

    # --- deeper nesting: GRUP inside GRUP inside GRUP ---
    deep_leaf = sub('EDID', zstr("FixtureDeepLeaf")) + sub('FULL', zstr("Deep Leaf"))
    lvl3 = group('ACHR', record('ACHR', 0x501, deep_leaf), group_type=1)
    lvl2 = group('ACHR', lvl3, group_type=1)
    lvl1 = group('CELL', lvl2, group_type=0)
    out += group('CELL', lvl1)

    # --- a couple of script records (Papyrus will need these later) ---
    scpt = sub('EDID', zstr("FixtureScript01")) + sub('MCSS', b'\x00' * 64)
    out += group('SCPT', record('SCPT', 0x600, scpt))

    return bytes(out)


if __name__ == '__main__':
    out_dir = sys.argv[1] if len(sys.argv) > 1 else 'data/esm_fixture'
    os.makedirs(out_dir, exist_ok=True)
    data = build()
    path = os.path.join(out_dir, 'Skyrim.esm')
    with open(path, 'wb') as f:
        f.write(data)

    # A second file acting as a "plugin", to prove plugin indexing + ordering.
    plug = (record('TES4', 0, sub('HEDR', struct.pack('<fii', 1.7, 1, 0x000810)))
            + group('CELL', record('CELL', 0x210,
                                   sub('EDID', zstr("PluginCellOverride"))
                                   + sub('FULL', zstr("From Plugin")))))
    with open(os.path.join(out_dir, 'FixturePlugin.esp'), 'wb') as f:
        f.write(plug)

    print(f"wrote {path} ({len(data)} bytes)")
    print(f"wrote {os.path.join(out_dir, 'FixturePlugin.esp')} ({len(plug)} bytes)")
