"""Generate a synthetic Skyrim.esm for end-to-end tests of the cell system.

This is OUR OWN synthetic data written to the documented TES4 container layout;
no game content is involved and every name is invented. It exercises exactly the
structures the cell reader must handle, including the two that are easy to get
wrong against real files:

  * a ZLIB-compressed CELL record whose body is framed as
    u32 decompressed-size + zlib stream (the real ESM layout), proving the
    reader inflates compressed cells rather than silently dropping them;
  * two worldspaces that both define a cell at grid (0,0), proving the grid
    index is keyed by (worldspace, x, y), not by the coordinate pair alone;
  * a worldspace "persistent cell" placed as a direct child of the world's
    children group, colliding at (0,0) with a real cell of the same worldspace,
    proving the persistent cell is excluded from spatial indexing;
  * interior cells (no XCLC) under the top-level CELL group;
  * REFR and ACHR references with NAME (base object) and DATA (position).

Usage:  python make_cell_fixture.py <output-dir>
"""
import os
import struct
import sys
import zlib

# --- container primitives ---------------------------------------------------

def record(rtype: str, form_id: int, payload: bytes, compressed: bool = False) -> bytes:
    """A 24-byte record header + payload. Compressed bodies carry a u32 size."""
    flags = 0x00040000 if compressed else 0
    if compressed:
        data = struct.pack('<I', len(payload)) + zlib.compress(payload)
    else:
        data = payload
    hdr = (rtype.encode('ascii').ljust(4, b'\0')[:4]
           + struct.pack('<III', len(data), flags, form_id)
           + struct.pack('<HHHH', 0, 0, 44, 0))
    assert len(hdr) == 24, len(hdr)
    return hdr + data


def group(label, children: bytes, group_type: int = 0) -> bytes:
    """A 24-byte GRUP header + children. groupSize includes the header.

    `label` is either a 4-char string (top-level group names) or an int, which
    is the FormID used by worldspace children groups.
    """
    if isinstance(label, int):
        lab = struct.pack('<I', label)
    else:
        lab = label.encode('ascii').ljust(4, b'\0')[:4]
    body = lab + struct.pack('<i', group_type) + struct.pack('<HHI', 0, 0, 0)
    assert len(body) == 16, len(body)
    size = 24 + len(children)
    hdr = b'GRUP' + struct.pack('<I', size) + body
    assert len(hdr) == 24, len(hdr)
    return hdr + children


def sub(rtype: str, payload: bytes) -> bytes:
    return (rtype.encode('ascii').ljust(4, b'\0')[:4]
            + struct.pack('<H', len(payload)) + payload)


def zstr(s: str) -> bytes:
    return s.encode('ascii') + b'\0'


def data6(pos) -> bytes:
    """DATA is six floats: position xyz followed by rotation xyz. `pos` may be a\n    full six-tuple, or a three-tuple whose rotation defaults to zero."""
    xyz = tuple(pos)
    if len(xyz) == 3:
        xyz = xyz + (0.0, 0.0, 0.0)
    return struct.pack('<6f', *xyz)


def refr(form_id: int, base: int, pos, edid: str = '') -> bytes:
    payload = b''
    if edid:
        payload += sub('EDID', zstr(edid))
    payload += sub('NAME', struct.pack('<I', base))
    payload += sub('DATA', data6(pos))
    return record('REFR', form_id, payload)


def achr(form_id: int, base: int, pos, edid: str = '') -> bytes:
    payload = b''
    if edid:
        payload += sub('EDID', zstr(edid))
    payload += sub('NAME', struct.pack('<I', base))
    payload += sub('DATA', data6(pos))
    return record('ACHR', form_id, payload)


def cell_payload(edid: str, xclc=None) -> bytes:
    payload = sub('EDID', zstr(edid))
    if xclc is not None:
        payload += sub('XCLC', struct.pack('<ii', xclc[0], xclc[1]))
    return payload


# --- content ----------------------------------------------------------------

WS_A = 0x00000100
WS_B = 0x00000200


def build() -> bytes:
    out = bytearray()

    tes4 = (sub('HEDR', struct.pack('<fii', 1.7, 8, 0x000800))
            + sub('CNAM', zstr("Cell Fixture"))
            + sub('SNAM', zstr("Generated by make_cell_fixture.py - no game content")))
    out += record('TES4', 0, bytes(tes4))

    # --- WRLD group: two worldspaces ---------------------------------------
    wrld = b''

    # Worldspace A.
    wrld += record('WRLD', WS_A, sub('EDID', zstr("FixtureWorldA")))
    ws_a_children = b''

    # Persistent pseudo-cell: direct child of the children group, at (0,0),
    # stored COMPRESSED so inflation of a cell payload is exercised.
    pers = record('CELL', 0x00000300, cell_payload("WorldAPersistent", (0, 0)),
                  compressed=True)
    pers += group(0x00000300, refr(0x00000310, 0x00000910, (123456.0, -234567.0, 0.0)),
                  group_type=8)
    ws_a_children += pers

    # Real exterior cells live under an ExtBlock (gtype 4) -> ExtSubBlock (5).
    sub_block = b''
    c00 = record('CELL', 0x00000301, cell_payload("WorldACell00", (0, 0)))
    c00 += group(0x00000301, refr(0x00000320, 0x00000920, (10.0, 20.0, 30.0)), group_type=8)
    sub_block += c00

    # A compressed exterior cell with one REFR and one ACHR.
    c01 = record('CELL', 0x00000302, cell_payload("WorldACell01", (0, 1)), compressed=True)
    c01 += group(0x00000302,
                 refr(0x00000321, 0x00000921, (100.0, 4100.0, 50.0), "FixtureRefr")
                 + achr(0x00000322, 0x00000922, (200.0, 4200.0, 60.0), "FixtureAchr"),
                 group_type=8)
    sub_block += c01

    ws_a_children += group(0x00000000, group(0x00000000, sub_block, group_type=5),
                           group_type=4)
    wrld += group(WS_A, ws_a_children, group_type=1)

    # Worldspace B: also a cell at grid (0,0). Must not collide with A's, and is
    # nested under its own block groups (only the persistent cell is a direct
    # child of a worldspace's children group).
    wrld += record('WRLD', WS_B, sub('EDID', zstr("FixtureWorldB")))
    b_cell = record('CELL', 0x00000400, cell_payload("WorldBCell00", (0, 0)))
    b_cell += group(0x00000400, b'', group_type=8)
    ws_b_children = group(0x00000000, group(0x00000000, b_cell, group_type=5),
                          group_type=4)
    wrld += group(WS_B, ws_b_children, group_type=1)

    out += group('WRLD', wrld)

    # --- Top-level CELL group: interior cells ------------------------------
    interior = record('CELL', 0x00000500, cell_payload("FixtureInterior01"))
    interior += group(0x00000500, refr(0x00000510, 0x00000930, (1.5, 2.5, 3.5), "InteriorRefr"),
                      group_type=8)
    int_block = group(0x00000000, group(0x00000000, interior, group_type=3), group_type=2)
    out += group('CELL', int_block)

    return bytes(out)


if __name__ == '__main__':
    out_dir = sys.argv[1] if len(sys.argv) > 1 else 'data/cell_fixture'
    os.makedirs(out_dir, exist_ok=True)
    data = build()
    path = os.path.join(out_dir, 'Skyrim.esm')
    with open(path, 'wb') as f:
        f.write(data)
    print(f"wrote {path} ({len(data)} bytes)")
