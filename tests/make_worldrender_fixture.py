"""Generate a synthetic Skyrim.esm whose base objects carry MODL model paths.

No game content is involved: every name and path is invented. It exercises the
chain the render pipeline depends on -- cell -> REFR -> base record -> MODL ->
placed model -- including the two ways a reference contributes no geometry:

  * a REFR whose base FormID does not exist in the file (dangling reference);
  * a REFR whose base exists but carries no MODL subrecord (invisible object).

Both must be skipped silently rather than aborting the cell.

Usage:  python make_worldrender_fixture.py <output-dir>
"""
import os
import struct
import sys

# --- container primitives (same layout as make_cell_fixture.py) --------------


def record(rtype, form_id, payload):
    hdr = (rtype.encode('ascii').ljust(4, b'\0')[:4]
           + struct.pack('<III', len(payload), 0, form_id)
           + struct.pack('<HHHH', 0, 0, 44, 0))
    return hdr + payload


def group(label, children, group_type=0):
    if isinstance(label, int):
        lab = struct.pack('<I', label)
    else:
        lab = label.encode('ascii').ljust(4, b'\0')[:4]
    body = lab + struct.pack('<i', group_type) + struct.pack('<HHI', 0, 0, 0)
    size = 24 + len(children)
    return b'GRUP' + struct.pack('<I', size) + body + children


def sub(rtype, payload):
    return (rtype.encode('ascii').ljust(4, b'\0')[:4]
            + struct.pack('<H', len(payload)) + payload)


def zstr(s):
    return s.encode('ascii') + b'\0'


def stat(form_id, edid, model=None):
    payload = sub('EDID', zstr(edid))
    if model is not None:
        payload += sub('MODL', zstr(model))
    return record('STAT', form_id, payload)


def refr(form_id, base, pos):
    xyz = tuple(pos)
    if len(xyz) == 3:
        xyz = xyz + (0.0, 0.0, 0.0)
    payload = sub('NAME', struct.pack('<I', base))
    payload += sub('DATA', struct.pack('<6f', *xyz))
    return record('REFR', form_id, payload)


def cell_payload(edid, xclc):
    return sub('EDID', zstr(edid)) + sub('XCLC', struct.pack('<ii', *xclc))


# --- content -----------------------------------------------------------------

WS = 0x00000100
STAT_HOUSE = 0x00001000
STAT_BARREL = 0x00001001
STAT_NOMODEL = 0x00001002
MISSING = 0x00009999
CELL = 0x00000301

HOUSE_MODEL = "Architecture\\Fixture\\house01.nif"
BARREL_MODEL = "Clutter\\Fixture\\barrel01.nif"


def build():
    out = bytearray()

    tes4 = (sub('HEDR', struct.pack('<fii', 1.7, 8, 0x000800))
            + sub('CNAM', zstr("World-Render Fixture"))
            + sub('SNAM', zstr("Generated by make_worldrender_fixture.py")))
    out += record('TES4', 0, tes4)

    # --- STAT records with MODL --------------------------------------------
    stat_group = (stat(STAT_HOUSE, "FixtureStatHouse", HOUSE_MODEL)
                  + stat(STAT_BARREL, "FixtureStatBarrel", BARREL_MODEL)
                  + stat(STAT_NOMODEL, "FixtureStatNoModel"))
    out += group('STAT', stat_group)

    # --- WRLD with one exterior cell at (0,0) ------------------------------
    wrld = record('WRLD', WS, sub('EDID', zstr("FixtureWorld")))

    refs = (refr(0x00000310, STAT_HOUSE, (100.0, 200.0, 0.0))
            + refr(0x00000311, STAT_BARREL, (300.0, 400.0, 10.0))
            + refr(0x00000312, STAT_NOMODEL, (500.0, 600.0, 0.0))
            + refr(0x00000313, MISSING, (700.0, 800.0, 0.0)))

    cell = record('CELL', CELL, cell_payload("FixtureCell00", (0, 0)))
    cell += group(CELL, refs, group_type=8)

    children = group(0x00000000, group(0x00000000, cell, group_type=5), group_type=4)
    wrld += group(WS, children, group_type=1)
    out += group('WRLD', wrld)

    return bytes(out)


if __name__ == '__main__':
    out_dir = sys.argv[1] if len(sys.argv) > 1 else 'data/worldrender_fixture'
    os.makedirs(out_dir, exist_ok=True)
    path = os.path.join(out_dir, 'Skyrim.esm')
    with open(path, 'wb') as f:
        f.write(build())
    print(f"wrote {path}")
